import assert from 'node:assert/strict'

export async function verifyBeforeCoach(browser, origin) {
  for (const [width, height] of [[320, 693], [390, 844]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    const button = name => page.getByRole('button', { name, exact: true })
    const heading = name => page.getByRole('heading', { name, exact: true })
    const validateWidth = async () => {
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width)
    }
    await page.goto(origin + '/welcome')
    await button('ورود به حساب').click({ timeout: 5000 })
    await heading('ورود به حساب').waitFor()
    await validateWidth()
    await page.getByLabel('ایمیل', { exact: true }).fill('demo@example.com')
    await page.getByLabel('رمز عبور', { exact: true }).fill('Invalid123')
    await button('ورود به حساب').click()
    await page.getByRole('alert').waitFor()
    await button('رمز عبور را فراموش کرده‌اید؟').click()
    await heading('بازیابی رمز عبور').waitFor()
    await page.getByLabel('ایمیل', { exact: true }).fill('demo@example.com')
    await button('ارسال لینک بازیابی').click()
    await page.getByRole('dialog').getByRole('heading', { name: 'لینک بازیابی ارسال شد.' }).waitFor()
    await validateWidth()
    await button('ارسال مجدد لینک').click()
    await button('باز کردن لینک آزمایشی').click()
    await heading('ایجاد رمز عبور جدید').waitFor()
    await page.getByLabel('رمز عبور جدید', { exact: true }).fill('NewRaya123!')
    await page.getByLabel('تکرار رمز عبور جدید', { exact: true }).fill('Mismatch123!')
    await button('تغییر رمز عبور').click()
    assert.equal(await page.getByLabel('تکرار رمز عبور جدید', {exact:true}).getAttribute('aria-invalid'), 'true')
    await page.getByLabel('تکرار رمز عبور جدید', { exact: true }).fill('NewRaya123!')
    await button('تغییر رمز عبور').click()
    await heading('رمز عبور شما با موفقیت تغییر کرد.').waitFor()
    await validateWidth()
    await button('ورود به حساب').click()
    await page.getByLabel('ایمیل', { exact: true }).fill('demo@example.com')
    await page.getByLabel('رمز عبور', { exact: true }).fill('NewRaya123!')
    await button('ورود به حساب').click()
    await page.waitForURL('**/profile/1')
    const more = button('مشاهده همه حوزه‌ها')
    assert.ok(await more.evaluate(element => {
      const chevron = element.querySelector('svg:last-child path')
      return chevron && chevron.getAttribute('d') === 'M8 3.75 3.75 8 8 12.25'
        && !chevron.hasAttribute('transform')
        && chevron.getBoundingClientRect().right < element.querySelector('span').getBoundingClientRect().left
    }), 'the SVG chevron points left and stays to the left of the RTL label')
    const background = page.locator('h1')
    await more.click()
    const industry = page.getByRole('dialog', { name: 'انتخاب نوع کسب‌وکار' })
    await industry.waitFor()
    assert.ok(await background.evaluate(element => Boolean(element.closest('[inert]'))))
    const entry = await industry.evaluate(element => element.getAnimations()[0]?.effect.getKeyframes()[0].transform)
    assert.equal(entry, 'translateY(100%)')
    await page.keyboard.press('Escape')
    await page.waitForURL('**/profile/1')
    assert.ok(await more.evaluate(element => element === document.activeElement))
    await page.getByText('فروشگاه و خرده‌فروشی', { exact: true }).click()
    await more.click()
    await industry.waitFor()
    const search = page.getByRole('searchbox')
    await search.fill('هیچ‌نتیجه')
    await page.getByText('حوزه‌ای پیدا نشد.').waitFor()
    await search.fill('سلامت')
    await industry.getByRole('radio', { name: 'سلامت و زیبایی', exact: true }).waitFor()
    await search.fill('خرده فروشي')
    assert.ok(await industry.getByRole('radio', { name: 'فروش و توزیع', exact: true }).isChecked())
    await search.fill('صنعت')
    await industry.getByText('صنعت و تولید', { exact: true }).click()
    assert.ok(await industry.getByRole('radio', { name: 'صنعت و تولید', exact: true }).isChecked())
    assert.ok(await page.locator('input[aria-label="فروشگاه و خرده‌فروشی"]').isChecked(),
      'the committed choice remains checked behind the picker until confirmation')
    await button('تأیید انتخاب').click()
    await page.waitForURL('**/profile/1')
    await page.reload()
    assert.ok(await page.getByRole('radio', { name: 'صنعت و تولید' }).isChecked())
    const choose = name => page.getByRole('radio', { name, exact: true }).check()
    for (const [step, choice] of [[2,'کالا و محصول'],[3,'رشد'],[4,'رشد و فروش']]) {
      await button('ادامه').click()
      await page.waitForURL(`**/profile/${step}`)
      await choose(choice)
      await validateWidth()
    }
    await button('ادامه').click()
    const multiLineGaps = await page.getByRole('checkbox').evaluateAll(inputs =>
      inputs.map(input => {
        const card = input.closest('label')
        const text = card.querySelector('span')
        const bounds = card.getBoundingClientRect()
        const content = text.getBoundingClientRect()
        if (content.height <= parseFloat(getComputedStyle(card).lineHeight)) return null
        return [content.top - bounds.top, bounds.bottom - content.bottom]
      }).filter(Boolean)
    )
    assert.ok(multiLineGaps.length > 0)
    assert.ok(multiLineGaps.every(gaps => gaps.every(gap => gap >= 9)),
      'two-line options need breathing room above and below')
    if (width === 390) {
      const rowHeights = await page.getByRole('checkbox').evaluateAll(inputs =>
        inputs.map(input => Math.round(input.closest('label').getBoundingClientRect().height)))
      assert.ok(rowHeights.every(height => height === 54), 'reason cards match the 54px reference at 390px')
    }
    await page.getByRole('checkbox', { name: 'فروش کاهش پیدا کرده' }).check()
    await page.getByRole('checkbox', { name: 'چالش‌های تیمی' }).check()
    assert.ok(await page.getByRole('checkbox', { name: 'مشتری کافی نداریم' }).isDisabled())
    await button('ادامه').click()
    const goal = page.getByRole('textbox')
    await goal.fill('فروش ماهانه را افزایش دهم.')
    assert.deepEqual(await goal.evaluate(el => [
      getComputedStyle(el).outlineStyle,
      getComputedStyle(el.parentElement).borderTopColor,
    ]), ['none', 'rgb(184, 88, 42)'])
    await button('ادامه').click()
    await choose('۳ تا ۵ ساعت در هفته')
    await button('بازگشت').click()
    assert.equal(await goal.inputValue(), 'فروش ماهانه را افزایش دهم.')
    await page.reload()
    assert.equal(await goal.inputValue(), 'فروش ماهانه را افزایش دهم.')
    await button('ادامه').click()
    await button('شروع گفتگو').click()
    await page.waitForURL('**/home/start-session')
    await heading('شروع جلسهٔ اول با کوچ').waitFor()
    const startTime = Date.now()
    await button('شروع گفت‌وگو').click()
    await button('در حال ورود به جلسه…').waitFor()
    await page.waitForURL('**/coach/session/demo')
    assert.ok(Date.now() - startTime >= 1400)
    await button('شروع مکالمه').waitFor()
    await validateWidth()
    await page.goto(origin + '/password/reset?token=invalid')
    await heading('لینک بازیابی معتبر نیست.').waitFor()
    await page.close()
    console.log(`Sign-in, recovery and 7 profile steps verified at ${width}×${height}`)
  }
}
