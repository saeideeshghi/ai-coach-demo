import assert from 'node:assert/strict'

export async function verifyProgram(browser, origin) {
  for (const [width, height] of [[320, 693], [390, 844]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    const button = name => page.getByRole('button', { name, exact: true })
    const heading = name => page.getByRole('heading', { name, exact: true })
    await page.goto(origin + '/program/package/contents')
    const rows = page.getByRole('list').getByRole('button')
    assert.equal(await rows.count(), 7)
    for (const [index, count] of [8, 6, 9, 8, 7, 3, 4].entries()) {
      await rows.nth(index).click()
      await page.waitForURL('**/program/systems/*')
      await heading('زیرسیستم‌های بستهٔ جامع').waitFor()
      assert.equal(await page.getByRole('list', { name: 'زیرسیستم‌ها' }).getByRole('listitem').count(), count)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width)
      await button('بازگشت به جزئیات بسته').click()
      await page.waitForURL('**/program/package/contents')
    }
    await page.goto(origin + '/program/package?demo=incomplete')
    await button('ادامه و پرداخت').click()
    await page.waitForURL('**/checkout?demo=incomplete')
    await heading('بررسی سفارش و پرداخت').waitFor()
    await button('بازگشت به بسته').click()
    await page.waitForURL('**/program/package?demo=incomplete')
    await button('ادامه و پرداخت').click()
    await button('پرداخت آزمایشی').click()
    await heading('در حال انتقال به درگاه پرداخت').waitFor()
    await heading('در حال تأیید پرداخت').waitFor()
    await heading('پرداخت کامل نشد').waitFor()
    const orderUrl = page.url()
    await page.reload()
    await heading('پرداخت کامل نشد').waitFor()
    await button('تلاش دوباره').click()
    await heading('پرداخت با موفقیت انجام شد').waitFor()
    assert.equal(page.url(), orderUrl)
    await page.goto(origin + '/home')
    await heading('در حال آماده‌سازی برنامهٔ اختصاصی').waitFor()
    await page.goto(orderUrl)
    await button('مشاهدهٔ خلاصهٔ سفارش').click()
    await page.waitForURL('**/orders/*/receipt')
    await heading('خلاصهٔ سفارش').waitFor()
    await page.reload()
    await heading('محتوای سفارش').waitFor()
    await button('بازگشت به خانه').click()
    await heading('برنامه در حال آماده‌سازی است').waitFor()
    await button('بازگشت به خانه').click()
    await page.waitForURL('**/home')
    await heading('سیستم جاری').waitFor()
    await page.reload()
    await heading('سیستم جاری').waitFor()
    await page.close()
  }
  const page = await browser.newPage()
  await page.goto(origin + '/program/package?demo=unknown')
  await page.getByRole('button', { name: 'ادامه و پرداخت' }).click()
  await page.getByRole('button', { name: 'پرداخت آزمایشی' }).click()
  await page.getByRole('heading', { name: 'نتیجهٔ پرداخت هنوز مشخص نیست' }).waitFor()
  await page.getByRole('button', { name: 'بررسی وضعیت پرداخت' }).click()
  await page.getByRole('heading', { name: 'در حال تأیید پرداخت' }).waitFor()
  await page.getByRole('heading', { name: 'پرداخت با موفقیت انجام شد' }).waitFor()
  await page.goto(origin + '/orders/nonexistent/receipt')
  await page.getByText('سفارش در این تب پیدا نشد.').waitFor()
  await page.close()
  console.log('Program systems, demo payment outcomes, receipt and preparing home verified')
}
