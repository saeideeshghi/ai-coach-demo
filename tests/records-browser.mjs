import assert from 'node:assert/strict'

export async function verifyRecords(browser, origin) {
  for (const [width, height] of [[320, 693], [390, 844]]) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce', acceptDownloads: true })
    const button = name => page.getByRole('button', { name, exact: true })
    try {
      await page.goto(origin + '/home')
      await page.evaluate(() => sessionStorage.setItem('raya-demo-package-order', '{'))
      await page.reload()
      await button('آموزش').click({ timeout: 4000 })
      await page.waitForURL('**/courses')
      await button('سوابق').click()
      await page.waitForURL('**/history')
      assert.equal(await button('سوابق').getAttribute('aria-current'), 'page')
      await page.getByRole('heading', { name: 'سوابق', exact: true }).waitFor()
      await page.getByText('هنوز سابقه‌ای ثبت نشده است.', { exact: true }).waitFor()
      assert.equal(await page.getByRole('list', { name: 'درس‌های دوره' }).count(), 0)
      await button('بازگشت').click()
      await page.waitForURL('**/courses')
      await page.goto(origin + '/courses/unknown/lessons/unknown')
      await page.getByRole('heading', { name: 'محتوای آموزشی پیدا نشد' }).waitFor()
      await button('بازگشت').click()
      await page.waitForURL('**/courses')

      await page.goto(origin + '/home')
      await button('منوی برنامه').click()
      await button('تقویم جلسات').click()
      await page.waitForURL('**/sessions/calendar')
      const firstDay = await page.getByRole('button', { name: /^۱ شهریور ۱۴۰۵/ }).boundingBox()
      const sunday = await page.getByText('یکشنبه', { exact: true }).boundingBox()
      assert.ok(firstDay && sunday && Math.abs(firstDay.x + firstDay.width / 2 - sunday.x - sunday.width / 2) <= 1)
      await page.getByRole('button', { name: /کوچینگ رشد کسب‌وکار/ }).click()
      await page.waitForURL('**/sessions/sh-18-am')
      await page.getByRole('heading', { name: 'جزئیات جلسهٔ کوچینگ' }).waitFor()
      await button('مشاهدهٔ ضبط جلسه').click()
      await page.locator('video').waitFor()
      await button('بازگشت', { exact: true }).click()
      await page.waitForURL('**/sessions/calendar')
      await page.getByRole('button', { name: /مرور اهداف و برنامه‌ریزی/ }).click()
      await page.waitForURL('**/sessions/sh-18-pm')
      await page.getByRole('heading', { name: 'مرور اهداف و برنامه‌ریزی' }).waitFor()
      await button('بازگشت').click()
      await button('ماه قبل').click()
      await page.waitForURL('**/sessions/calendar?month=mordad&day=8')
      await page.getByRole('button', { name: /جلسهٔ مرور مسیر رشد/ }).click()
      await page.waitForURL('**/sessions/mor-8')
      await button('بازگشت').click()
      await page.waitForURL('**/sessions/calendar?month=mordad&day=8')
      await button('بازگشت').click()
      await page.waitForURL('**/home')

      await page.goto(origin + '/home')
      await button('منوی برنامه').click()
      await button('یادداشت‌های من').click()
      await page.evaluate(() => sessionStorage.setItem('raya-records:notes', '{}'))
      await page.reload()
      await button('افزودن یادداشت').click()
      await page.getByRole('textbox', { name: 'عنوان یادداشت' }).fill('یادداشت آزمایشی رایا')
      await page.getByRole('textbox', { name: 'متن یادداشت' }).fill('متن راست‌چین آزمایشی')
      await page.getByRole('combobox', { name: 'جلسهٔ مرتبط' }).selectOption('sh-18-am')
      const saveNote = button('ذخیرهٔ یادداشت')
      assert.match(await saveNote.evaluate(node => getComputedStyle(node).backgroundImage), /linear-gradient/)
      await saveNote.click()
      await page.waitForURL('**/notes')
      await page.reload()
      await page.getByRole('searchbox').fill('یادداشت آزمایشی رایا')
      await page.getByRole('button', { name: /یادداشت آزمایشی رایا/ }).click()
      assert.equal(await page.getByRole('combobox', { name: 'جلسهٔ مرتبط' }).inputValue(), 'sh-18-am')
      await button('انصراف').click()

      await page.goto(origin + '/home')
      await button('اعلان‌ها').click()
      await page.getByRole('button', { name: /جلسهٔ بعدی/ }).click()
      await page.waitForURL('**/sessions/sh-22')
      await page.getByText('جلسهٔ زمان‌بندی‌شده', { exact: true }).waitFor()
      assert.equal(await button('مشاهدهٔ ضبط جلسه').count(), 0)
      await button('بازگشت').click()
      await page.waitForURL('**/notifications')
      await button('خوانده‌شده').click()
      assert.equal(await page.getByRole('button', { name: /جلسهٔ بعدی/ }).count(), 1)
      await button('تنظیمات اعلان‌ها').click()
      await page.waitForURL('**/account')
      await button('ویرایش اطلاعات حساب').click()
      await page.getByRole('textbox', { name: 'عنوان شغلی' }).fill('مدیر محصول')
      await button('ذخیره تغییرات').click()
      await page.waitForURL('**/account')
      await page.reload()
      await page.getByText('مدیر محصول', { exact: true }).waitFor()

      await page.goto(origin + '/home?demo=resume')
      await button('ادامهٔ مسیر').click()
      await page.waitForURL(/\/actions\//)
      await page.goto(origin + '/followup')
      await page.getByRole('button', { name: /همهٔ سیستم‌ها/ }).click()
      await page.waitForURL('**/followup/systems')
      await page.getByRole('heading', { name: '۰ از ۷ سیستم تکمیل شده' }).waitFor()
      await button('بازگشت به اقدام جاری').click()
      await page.waitForURL('**/followup')

      await page.goto(origin + '/home?demo=one-system')
      await button('مشاهدهٔ وضعیت سیستم‌ها').click()
      await page.waitForURL('**/followup/systems')
      await page.getByRole('heading', { name: '۱ از ۷ سیستم تکمیل شده' }).waitFor()
      await button('بازگشت به برنامه').click()
      await page.waitForURL('**/home')
      await page.goto(origin + '/reports/final')
      await page.getByText('گزارش نهایی پس از تکمیل هفت سیستم آماده می‌شود.').waitFor()

      await page.goto(origin + '/home?demo=complete')
      await button('مشاهدهٔ گزارش نهایی').waitFor()
      await button('پیگیری').click()
      await page.waitForURL('**/followup')
      await page.getByRole('heading', { name: 'برنامهٔ هفت سیستم تکمیل شد' }).waitFor()
      const report = button('مشاهدهٔ گزارش نهایی')
      const reportBox = await report.boundingBox()
      assert.ok(reportBox && reportBox.y + reportBox.height <= height)
      await report.click()
      await page.waitForURL('**/reports/final')
      await page.getByRole('button', { name: /جمع‌بندی مدیریتی/ }).click()
      await page.waitForURL('**/reports/final/details')
      await page.getByRole('heading', { name: 'میزان تحقق اهداف' }).waitFor()
      const downloadReport = button('دریافت گزارش نهایی')
      assert.match(await downloadReport.evaluate(node => getComputedStyle(node).backgroundImage), /linear-gradient/)
      const [download] = await Promise.all([page.waitForEvent('download'), downloadReport.click()])
      assert.match(download.suggestedFilename(), /رایا/)
      await button('بازگشت').click()
      await page.waitForURL('**/reports/final')
      await button('بازگشت').click()
      await page.waitForURL('**/followup')
      await button('سوابق').click()
      await page.waitForURL('**/history')
      await page.getByText('هنوز سابقه‌ای ثبت نشده است.', { exact: true }).waitFor()
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    } finally { await page.close() }
  }
  console.log('History, calendar, notes, notifications, account, program progress and final report verified')
}
