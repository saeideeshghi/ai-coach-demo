import assert from 'node:assert/strict'

export async function verifyCoach(browser, origin) {
  for (const [width, height] of [[320, 693], [390, 844]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    const button = name => page.getByRole('button', { name, exact: true })
    await page.goto(origin + '/coach/session/demo')
    const ready = await button('شروع مکالمه').boundingBox({ timeout: 5000 })
    assert.ok(ready)
    await page.evaluate(() => {
      window.rayaMicPulses = 0
      document.addEventListener('animationstart', event => {
        if (event.target.matches('[data-voice-pulse]')) window.rayaMicPulses++
      })
    })
    await button('شروع مکالمه').click({ timeout: 5000 })
    await page.waitForFunction(() => window.rayaMicPulses === 1, null, { timeout: 2000 })
    await page.waitForFunction(() => {
      const video = document.querySelector('video')
      return video && !video.paused && video.currentTime > 0
    })
    const video = page.locator('video')
    const playing = await button('مکث مکالمه').boundingBox()
    assert.ok(playing)
    assert.equal(ready.y + ready.height / 2, playing.y + playing.height / 2, 'voice controls stay anchored across playback')
    assert.equal(await page.locator('[data-speech-level]').count(), 0, 'the microphone stays visible during the silent lead-in')
    await video.evaluate(element => { element.currentTime = 5.75 })
    await page.locator('[data-speech-level]').waitFor()
    assert.ok(Number(await page.locator('[data-speech-level]').getAttribute('data-speech-level')) > 0)
    await button('مکث مکالمه').click()
    await button('ادامه مکالمه').waitFor()
    const pausedAt = await video.evaluate(element => element.currentTime)
    assert.ok(pausedAt > 0)
    await button('ادامه مکالمه').click()
    await button('مکث مکالمه').waitFor()
    assert.equal(await page.evaluate(() => window.rayaMicPulses), 1)
    assert.ok(await video.evaluate(element => element.currentTime) >= pausedAt)
    await button('صفحه چت').click()
    const draft = page.getByRole('textbox', { name: 'متن پیام' })
    assert.ok(await button('ارسال پیام').isDisabled())
    if (width === 390) {
      const log = await page.getByRole('log').boundingBox()
      const composer = await draft.locator('xpath=..').boundingBox()
      assert.deepEqual([Math.round(log.width), Math.round(log.height)], [358, 274])
      assert.deepEqual([Math.round(composer.width), Math.round(composer.height)], [343, 39])
    }
    await draft.fill('چطور فروش را بهبود بدهم؟')
    await page.mouse.click(width * 0.5, height * 0.25)
    await draft.waitFor({ state: 'hidden', timeout: 5000 })
    await button('مکث مکالمه').waitFor()
    await button('صفحه چت').click()
    assert.equal(await draft.inputValue(), 'چطور فروش را بهبود بدهم؟')
    await button('ارسال پیام').click()
    assert.equal(await page.locator('[data-typing-dot]').count(), 3)
    await page.getByText('چطور فروش را بهبود بدهم؟', { exact: true }).waitFor()
    await page.getByText('برای شروع، نرخ تبدیل و دلیل از دست رفتن مشتریان را بررسی کنید.', { exact: true }).waitFor()
    await draft.fill('این متن بلند برای آزمودن پیمایش چت است. '.repeat(24).trim())
    await button('ارسال پیام').click()
    await page.getByText('یک نمونهٔ مشخص از این چالش را بگویید تا بتوانیم قدم بعدی را انتخاب کنیم.', { exact: true }).waitFor()
    const history = page.getByRole('log')
    assert.ok(await history.evaluate(el => el.scrollHeight > el.clientHeight))
    await history.focus()
    await page.keyboard.press('Control+Home')
    await page.waitForFunction(() => document.querySelector('[role="log"]')?.scrollTop === 0)
    await button('بازگشت به مکالمه صوتی').click()
    await button('تنظیمات صدا').click()
    const dialog = page.getByRole('dialog', { name: 'تنظیمات صدا' })
    const close = button('بستن تنظیمات')
    await dialog.evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished)))
    const markBounds = await close.locator('svg').boundingBox()
    const closeBounds = await close.boundingBox()
    assert.ok(markBounds && closeBounds)
    assert.equal(markBounds.x + markBounds.width / 2, closeBounds.x + closeBounds.width / 2)
    assert.equal(markBounds.y + markBounds.height / 2, closeBounds.y + closeBounds.height / 2)
    assert.equal(await video.evaluate(element => element.paused), true)
    await button('شنیدن نمونه صدا').click()
    await button('توقف نمونه صدا').waitFor()
    assert.equal(await button('توقف نمونه صدا').locator('[data-moving]').getAttribute('data-moving'), 'false')
    assert.equal(await video.evaluate(element => element.paused), true)
    await dialog.getByRole('radio', { name: /سریع/ }).check()
    await page.mouse.click(8, 8)
    await dialog.waitFor({ state: 'hidden' })
    await button('تنظیمات صدا').click()
    assert.ok(await dialog.getByRole('radio', { name: /معمولی/ }).isChecked())
    await dialog.getByRole('radio', { name: /صدای دوم/ }).check()
    await dialog.getByText('نمونهٔ صدای دوم در دمو موجود نیست.').waitFor()
    await dialog.getByRole('radio', { name: /سریع/ }).check()
    await button('ذخیره تنظیمات').click()
    await button('تنظیمات صدا').click()
    assert.ok(await dialog.getByRole('radio', { name: /سریع/ }).isChecked())
    await button('بازگرداندن تنظیمات پیش‌فرض').click()
    assert.ok(await dialog.getByRole('radio', { name: /معمولی/ }).isChecked())
    await button('ذخیره تنظیمات').click()
    await page.waitForFunction(() => !document.querySelector('video').paused)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width)
    await video.evaluate(element => { element.currentTime = element.duration - 0.1 })
    await page.getByRole('heading', { name: 'جلسهٔ رایگان شما به پایان رسید.' }).waitFor()
    assert.equal(await page.locator('video').evaluate(video => video.paused), true)
    await button('مشاهدهٔ جمع‌بندی جلسه').click()
    await page.waitForURL('**/coach/session/demo/summary')
    await page.getByRole('heading', { name: 'جمع‌بندی جلسهٔ رایگان' }).waitFor()
    await page.getByRole('heading', { name: 'دغدغه‌های شناسایی‌شده' }).waitFor()
    await page.getByRole('heading', { name: 'پیشنهاد کوچ برای شروع' }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width)
    await page.reload()
    await page.getByRole('heading', { name: 'جمع‌بندی جلسهٔ رایگان' }).waitFor()
    const summaryUrl = origin + '/coach/session/demo/summary'
    const nav = page.getByRole('navigation', { name: 'نوار اصلی' })
    await nav.getByRole('button', { name: 'خانه' }).waitFor()
    const arrow = button('ثبت اصلاحیه').locator('svg path')
    assert.equal(await arrow.getAttribute('d'), 'M8 3.75 3.75 8 8 12.25')
    const highlight = page.getByRole('heading', { name: 'پیشنهاد کوچ برای شروع' }).locator('..')
    assert.match(await highlight.evaluate(element => getComputedStyle(element).backgroundImage), /rgb\(29, 23, 21\), rgb\(23, 23, 25\)/)
    const navBox = await nav.boundingBox()
    const actionBox = await button('ثبت اصلاحیه').boundingBox()
    assert.ok(navBox.y >= actionBox.y + actionBox.height, 'the fixed bar leaves both summary actions clear')
    if (width === 390) {
      assert.deepEqual([navBox.x, navBox.y, navBox.width, navBox.height].map(Math.round), [16, 763, 358, 67])
      assert.deepEqual([actionBox.x, actionBox.y, actionBox.width, actionBox.height].map(Math.round), [16, 698, 157, 52])
      const lineHeights = await page.locator('[data-variant=summary]').evaluate(frame =>
        [...frame.querySelectorAll('h2 + p, h2 + ul li, h2 + strong + p')].map(element => getComputedStyle(element).lineHeight))
      assert.deepEqual(lineHeights, ['21px', '21px', '21px', '21px', '20px'])
    }
    await button('ثبت اصلاحیه').click()
    await page.waitForURL('**/summary/correction')
    assert.equal(await button('انصراف').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(22, 23, 25)')
    await button('ثبت یادداشت').click()
    await page.getByText('توضیح خود را وارد کنید.', { exact: true }).waitFor()
    const note = page.getByRole('textbox', { name: 'توضیح شما' })
    await note.fill('اولویت من مسئولیت‌های تیم فروش است.')
    await button('ثبت یادداشت').click()
    await page.waitForURL('**/summary/saved')
    await page.getByRole('heading', { name: 'یادداشت شما ثبت شد' }).waitFor()
    const coveredForm = page.locator('[data-sheet=correction][inert]')
    assert.equal(await coveredForm.locator('textarea').inputValue(), 'اولویت من مسئولیت‌های تیم فروش است.')
    await page.reload()
    await button('بازگشت به جمع‌بندی').click()
    await page.waitForURL(summaryUrl)
    await button('ثبت اصلاحیه').click()
    assert.equal(await note.inputValue(), 'اولویت من مسئولیت‌های تیم فروش است.')
    await button('انصراف').click()
    await button('مشاهدهٔ بسته و تعرفه‌ها').click()
    await page.waitForURL('**/program/package')
    await page.getByRole('heading', { name: 'بستهٔ جامع و پرداخت' }).waitFor()
    await button('جزئیات هفت سیستم و زیرسیستم‌ها').click()
    await page.waitForURL('**/program/package/contents')
    await button('بازگشت').click()
    await page.waitForURL('**/program/package')
    await button('بازگشت').click()
    await page.waitForURL(summaryUrl)
    await nav.getByRole('button', { name: 'خانه' }).click()
    await page.waitForURL('**/home')
    await page.getByRole('heading', { name: 'فعالیت‌های اخیر' }).waitFor()
    await button('جمع‌بندی و پیشنهاد کوچ').click()
    await page.waitForURL(summaryUrl)
    await page.close()
    console.log(`Coach demo and summary verified at ${width}×${height}`)
  }

  const reduced = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  await reduced.goto(origin + '/coach/session/demo')
  await reduced.getByRole('button', { name: 'شروع مکالمه' }).click()
  const wave = reduced.locator('svg[data-moving="true"]')
  await wave.waitFor()
  assert.equal(await wave.locator('path').first().evaluate(el => getComputedStyle(el).animationName), 'none')
  await reduced.close()

  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await page.route('**/*.mp4', route => route.abort())
  await page.goto(origin + '/coach/session/demo')
  await page.getByRole('button', { name: 'شروع مکالمه' }).click()
  await page.getByRole('alert').getByText('پخش ویدیوی دمو ممکن نشد.').waitFor()
  await page.getByRole('button', { name: 'تلاش دوباره' }).waitFor()
  await page.close()
}
